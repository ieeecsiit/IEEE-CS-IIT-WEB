-- Forms built in /admin. `definition` is the current FormDefinition JSON (shared/forms.ts).
CREATE TABLE forms (
  id          TEXT PRIMARY KEY,
  slug        TEXT NOT NULL UNIQUE,
  definition  TEXT NOT NULL,
  version     INTEGER NOT NULL DEFAULT 1,
  is_open     INTEGER NOT NULL DEFAULT 0,
  created_at  TEXT NOT NULL,
  updated_at  TEXT NOT NULL,
  updated_by  TEXT NOT NULL DEFAULT ''
);

-- Every saved version, so old responses are always shown with the questions they answered.
CREATE TABLE form_versions (
  form_id     TEXT NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
  version     INTEGER NOT NULL,
  definition  TEXT NOT NULL,
  created_at  TEXT NOT NULL,
  created_by  TEXT NOT NULL DEFAULT '',
  PRIMARY KEY (form_id, version)
);

-- One row per submission. `id` is generated by the browser, so a retried submission is stored once.
CREATE TABLE responses (
  id            TEXT PRIMARY KEY,
  form_id       TEXT NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
  form_version  INTEGER NOT NULL,
  answers       TEXT NOT NULL,
  files         TEXT NOT NULL DEFAULT '{}',
  dedupe_key    TEXT,
  status        TEXT NOT NULL DEFAULT 'new',
  notes         TEXT NOT NULL DEFAULT '',
  created_at    TEXT NOT NULL,
  updated_at    TEXT,
  updated_by    TEXT
);
CREATE UNIQUE INDEX responses_one_per_person ON responses (form_id, dedupe_key) WHERE dedupe_key IS NOT NULL;
CREATE INDEX responses_by_form ON responses (form_id, created_at DESC);

-- Who changed what in the admin panel.
CREATE TABLE audit_log (
  id      INTEGER PRIMARY KEY AUTOINCREMENT,
  at      TEXT NOT NULL,
  actor   TEXT NOT NULL,
  action  TEXT NOT NULL,
  target  TEXT NOT NULL DEFAULT '',
  detail  TEXT NOT NULL DEFAULT ''
);
CREATE INDEX audit_log_at ON audit_log (at DESC);
